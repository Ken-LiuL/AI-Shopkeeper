def print_stats() -> None:
    """打印 FAQ 统计。"""
    categories: dict[str, int] = {}
    for faq in FAQS:
        cat = faq["category"]
        categories[cat] = categories.get(cat, 0) + 1

    print("=" * 60)
    print("📊 FAQ 种子数据统计")
    print("=" * 60)
    print(f"  总 FAQ 数量:  {len(FAQS)}")
    print("  ────────────────────────────")
    for cat, count in sorted(categories.items(), key=lambda x: -x[1]):
        print(f"  {cat}: {count} 条")
    print("=" * 60)


def dry_run() -> None:
    """只打印 FAQ 数据，不写入数据库。"""
    print_stats()
    print("\n🔍 Dry-run 模式 — FAQ 数据预览:\n")
    for faq in FAQS:
        print(f"[{faq['id']}] ({faq['category']}) Q: {faq['question']}")
        print(f"  A: {faq['answer'][:80]}...")
        print(f"  Keywords: {faq['keywords']}")
        if faq.get("related_products"):
            print(f"  Related: {faq['related_products']}")
        print()
    print(f"✅ 共 {len(FAQS)} 条 FAQ，dry-run 完成，无语法错误。")


def seed_neo4j(url: str, user: str, password: str) -> None:
    """将 FAQ 写入 Neo4j。"""
    from neo4j import GraphDatabase  # type: ignore[import-untyped]

    print("[Neo4j] Connecting …")
    driver = GraphDatabase.driver(url, auth=(user, password))

    with driver.session() as session:
        # 创建约束
        session.run("CREATE CONSTRAINT IF NOT EXISTS FOR (f:FAQ) REQUIRE f.faq_id IS UNIQUE")

        # 写入 FAQ 节点
        for faq in FAQS:
            session.run(
                """MERGE (f:FAQ {faq_id: $fid})
                   SET f.question = $q, f.answer = $a,
                       f.category = $cat,
                       f.keywords = $kw,
                       f.question_embedding = null""",
                fid=faq["id"],
                q=faq["question"],
                a=faq["answer"],
                cat=faq["category"],
                kw=faq["keywords"],
            )

            # 关联商品
            for pid in faq.get("related_products", []):
                session.run(
                    """MATCH (f:FAQ {faq_id: $fid}), (p:Product {product_id: $pid})
                       MERGE (f)-[:ANSWERS]->(p)""",
                    fid=faq["id"],
                    pid=pid,
                )

    driver.close()
    print_stats()
    print("\n[Neo4j] Done ✅")


def main() -> None:
    parser = argparse.ArgumentParser(description="AI店长 FAQ 种子数据")
    parser.add_argument("--neo4j-url", default="bolt://localhost:7687")
    parser.add_argument("--neo4j-user", default="neo4j")
    parser.add_argument("--neo4j-password", default="neo4jpassword")
    parser.add_argument("--dry-run", action="store_true", help="只打印统计和预览，不写入数据库")
    args = parser.parse_args()

    if args.dry_run:
        dry_run()
    else:
        seed_neo4j(args.neo4j_url, args.neo4j_user, args.neo4j_password)


if __name__ == "__main__":
    main()
